//! Usage text, per-tool help, the tool list and the generated Markdown reference
//! (`engram tools --markdown` writes docs/wiki/en/tools.md).

use engram_proto::tools::{self, Access, ToolDef, GROUPS};
use std::fmt::Write;
use std::process::ExitCode;

pub const USAGE: &str = "\
Engram — AI-native memory scanner for Linux games (native, Wine and Proton)

USAGE
  engram <tool> [key=value ...]     call a tool, e.g. `engram scan value=100`
  engram <tool> '<json>'            same, with JSON arguments
  engram tools [--markdown]         list tools (or print the Markdown reference)
  engram help <tool>                arguments and an example for a tool

SETUP & AGENTS
  engram doctor                     check permissions, the engine and agents
  engram setup                      one-time: let the engine read your programs (asks for your password)
  engram agent-init [dir]           write AGENTS.md + OpenCode/Claude MCP config into dir (default: .)
  engram mcp                        run the MCP server on stdio (for agent configs)

SETTINGS
  engram config                     show all settings
  engram config set <key> <value>   change one (`engram config reset [key]` restores defaults)

OTHER
  engram launch -- <cmd> [args]     run a program as Engram's child (works without `setup`;
                                    Steam launch option: engram launch -- %command%)
  engram events                     stream live session events
  engram daemon start|stop|status   manage the background engine
  engram uninstall [--purge]        remove Engram (--purge: also settings, tables, logs)
  engram version

Output is JSON (pretty in a terminal, compact otherwise; --pretty/--compact to force).
";

fn required(t: &ToolDef) -> Vec<&str> {
    t.schema["required"].as_array().map(|a| a.iter().filter_map(|v| v.as_str()).collect()).unwrap_or_default()
}

pub fn tool(name: Option<&str>) -> ExitCode {
    let Some(name) = name else {
        print!("{USAGE}");
        return ExitCode::SUCCESS;
    };
    let Some(t) = tools::find(name) else {
        eprintln!("unknown tool '{name}'; run `engram tools`");
        return ExitCode::from(2);
    };
    println!("{} — {}\n", t.name, t.summary);
    println!("{}\n", textwrap(t.description, 92));
    let props = t.schema["properties"].as_object().cloned().unwrap_or_default();
    let req = required(t);
    if !props.is_empty() {
        println!("ARGUMENTS");
        for (k, v) in &props {
            let ty = v.get("type").and_then(|t| t.as_str()).unwrap_or("any");
            let r = if req.contains(&k.as_str()) { " (required)" } else { "" };
            let def = v.get("default").map(|d| format!(" [default {d}]")).unwrap_or_default();
            let desc = v.get("description").and_then(|d| d.as_str()).unwrap_or("");
            println!("  {k:<16} {ty}{r}{def}  {desc}");
        }
        println!();
    }
    if t.access == Access::Mutate {
        println!("Agents need the user's approval in the Engram window for this tool.\n");
    }
    println!("EXAMPLE\n  engram {} '{}'", t.name, t.example);
    ExitCode::SUCCESS
}

pub fn list(markdown: bool) -> ExitCode {
    if markdown {
        print!("{}", markdown_reference());
        return ExitCode::SUCCESS;
    }
    for (group, title) in GROUPS {
        println!("{title}");
        for t in tools::catalog().iter().filter(|t| t.group == *group) {
            let tag = if t.access == Access::Mutate { " [approval]" } else { "" };
            println!("  {:<16} {}{}", t.name, t.summary, tag);
        }
        println!();
    }
    ExitCode::SUCCESS
}

fn markdown_reference() -> String {
    let mut o = String::from(
        "<!-- Generated by `engram tools --markdown`. Do not edit by hand. -->\n\
         # Tool reference\n\n\
         Every tool works the same from the CLI (`engram <tool> key=value`), over MCP\n\
         (`engram_<tool>` in most agents) and on the daemon socket. Tools marked\n\
         **approval** wait for the user's decision in the Engram window when an agent calls them.\n\n",
    );
    for (group, title) in GROUPS {
        let _ = writeln!(o, "## {title}\n");
        for t in tools::catalog().iter().filter(|t| t.group == *group) {
            let tag = if t.access == Access::Mutate { " · **approval**" } else { "" };
            let _ = writeln!(o, "### `{}`{tag}\n\n{}\n\n{}\n", t.name, t.summary, t.description);
            let props = t.schema["properties"].as_object().cloned().unwrap_or_default();
            if !props.is_empty() {
                let req = required(t);
                let _ = writeln!(o, "| Argument | Type | Default | Description |\n|---|---|---|---|");
                for (k, v) in &props {
                    let ty = v.get("type").and_then(|t| t.as_str()).unwrap_or("any");
                    let def = v.get("default").map(|d| format!("`{d}`")).unwrap_or_else(|| {
                        if req.contains(&k.as_str()) {
                            "required".into()
                        } else {
                            String::new()
                        }
                    });
                    let desc = v.get("description").and_then(|d| d.as_str()).unwrap_or("").replace('|', "\\|");
                    let _ = writeln!(o, "| `{k}` | {ty} | {def} | {desc} |");
                }
                o.push('\n');
            }
            let _ = writeln!(o, "```sh\nengram {} '{}'\n```\n", t.name, t.example);
        }
    }
    o
}

pub fn textwrap(s: &str, width: usize) -> String {
    let mut out = String::new();
    let mut line = 0;
    for w in s.split_whitespace() {
        if line + w.len() + 1 > width && line > 0 {
            out.push('\n');
            line = 0;
        } else if line > 0 {
            out.push(' ');
            line += 1;
        }
        out.push_str(w);
        line += w.len();
    }
    out
}
